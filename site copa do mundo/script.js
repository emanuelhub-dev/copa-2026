const matchesContainer = document.getElementById('matchesContainer');
const goalsTable = document.getElementById('goalsTable');
const assistsTable = document.getElementById('assistsTable');

let scorers = JSON.parse(localStorage.getItem('scorers')) || {};
let assists = JSON.parse(localStorage.getItem('assists')) || {};
let results = JSON.parse(localStorage.getItem('results')) || {};
let matchDetails = JSON.parse(
  localStorage.getItem('matchDetails')
) || {};
let savedMatches = JSON.parse(localStorage.getItem('savedMatches')) || {};

function renderMatches() {

  matchesContainer.innerHTML = '';

  const groupedMatches = {};

  matches.forEach(match => {

    if (!groupedMatches[match.date]) {
      groupedMatches[match.date] = [];
    }

    groupedMatches[match.date].push(match);

  });

  let globalIndex = 0;

  Object.keys(groupedMatches).forEach((date, dayIndex) => {

  const daySection = document.createElement('div');

daySection.innerHTML = `
<h2 class="day-title">
  <span class="arrow">
    ${dayIndex === 0 ? '▼' : '▶'}
  </span>
  📅 ${date}
  <span class="games-count">
    • ${groupedMatches[date].length} jogos
  </span>
</h2>
<div class="day-matches"></div>
`;

    const dayMatchesContainer =
      daySection.querySelector('.day-matches');
     if (dayIndex > 0) {
  dayMatchesContainer.style.display = 'none';
} 

    groupedMatches[date].forEach(match => {

      const card = document.createElement('div');

      card.classList.add('match-card');
      
      card.innerHTML = `

      ${savedMatches[globalIndex]
  ? '<div class="finished-badge">✓ Finalizada</div>'
  : ''
}
      
        <div class="match-header">

          <div class="match-date">
            ${match.date}
          </div>

          <div class="match-time">
            ${match.time}
          </div>

        </div>

        <div class="teams">

          <div class="team">${match.home}</div>

          <div class="score">

            <input
              type="number"
              min="0"
              value="${results[globalIndex]?.home || 0}"
              id="home-score-${globalIndex}"
              class="score-input"
            >

            <span>x</span>

            <input
              type="number"
              min="0"
              value="${results[globalIndex]?.away || 0}"
              id="away-score-${globalIndex}"
              class="score-input"
            >

          </div>

          <div class="team">${match.away}</div>

        </div>

        ${!savedMatches[globalIndex] ? `

<div class="inputs">

  <input
    type="text"
    id="goal-${globalIndex}"
    placeholder="Quem fez os gols?"
  >

  <input
    type="text"
    id="assist-${globalIndex}"
    placeholder="Quem deu assistência?"
  >

</div>

` : ''}

        ${matchDetails[globalIndex] ? `

<div class="match-details">

  <div class="goals-list">
    ⚽ ${matchDetails[globalIndex].goals.join(', ')}
  </div>

  <div class="assists-list">
    🎯 ${matchDetails[globalIndex].assists.join(', ')}
  </div>

</div>

` : ''}
    ${!savedMatches[globalIndex] ? `

<button
  class="save-btn"
  data-index="${globalIndex}"
>
  Salvar Estatísticas
</button>

` : ''}
      `;

      dayMatchesContainer.appendChild(card);

      globalIndex++;

    });

    matchesContainer.appendChild(daySection);
  const title =
  daySection.querySelector('.day-title');

const matchesDiv =
  daySection.querySelector('.day-matches');

if (dayIndex === 0) {

  matchesDiv.style.display = 'grid';

} else {

  matchesDiv.style.display = 'none';

}

title.addEventListener('click', () => {

  const arrow =
    title.querySelector('.arrow');

  if (matchesDiv.style.display === 'none') {

    matchesDiv.style.display = 'grid';

    arrow.textContent = '▼';

  } else {

    matchesDiv.style.display = 'none';

    arrow.textContent = '▶';

  }

});
  });

  const buttons =
    document.querySelectorAll('.save-btn');

  buttons.forEach(button => {

    button.addEventListener('click', () => {

      const index = button.dataset.index;

      saveMatch(index);

    });

  });

}

function saveMatch(index) {

  if (savedMatches[index]) {

  alert('Essa partida já foi contabilizada.');

  return;
}

  const goalInput = document.getElementById(`goal-${index}`).value;

  const assistInput = document.getElementById(`assist-${index}`).value;

  const homeScore =
document.getElementById(`home-score-${index}`).value;

const awayScore =
document.getElementById(`away-score-${index}`).value;

  const goalPlayers = goalInput
    .split(',')
    .map(player => player.trim())
    .filter(player => player !== '');

  const assistPlayers = assistInput
    .split(',')
    .map(player => player.trim())
    .filter(player => player !== '');

  goalPlayers.forEach((player) => {

    scorers[player] = (scorers[player] || 0) + 1;

  });

  assistPlayers.forEach((player) => {

    assists[player] = (assists[player] || 0) + 1;

  });

  localStorage.setItem('scorers', JSON.stringify(scorers));

  localStorage.setItem('assists', JSON.stringify(assists));

  results[index] = {

  home: homeScore,

  away: awayScore

};

matchDetails[index] = {

  goals: goalPlayers,

  assists: assistPlayers

};

localStorage.setItem(
  'matchDetails',
  JSON.stringify(matchDetails)
);

localStorage.setItem(
  'results',
  JSON.stringify(results)
);

savedMatches[index] = true;

localStorage.setItem(
  'savedMatches',
  JSON.stringify(savedMatches)
);

renderMatches();

  renderTables();

  alert('Estatísticas salvas!');

}

function renderTables() {

  goalsTable.innerHTML = '';

  assistsTable.innerHTML = '';

  Object.entries(scorers)
    .sort((a, b) => b[1] - a[1])
    .forEach(([player, goals]) => {

      goalsTable.innerHTML += `
        <tr>
          <td>${player}</td>
          <td>${goals}</td>
        </tr>
      `;

    });

  Object.entries(assists)
    .sort((a, b) => b[1] - a[1])
    .forEach(([player, total]) => {

      assistsTable.innerHTML += `
        <tr>
          <td>${player}</td>
          <td>${total}</td>
        </tr>
      `;

      });

      function limparDados() {

  localStorage.clear();

  location.reload();

}
}


renderMatches();

renderTables();

